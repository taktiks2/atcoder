// algo: simulation, math, greedy
use proconio::{fastout, input};

// 買い物は互いに独立なので、1 回ずつ処理して枚数を足し込むだけでよい。O(N)。
//
// A_i 円に対して出す紙幣は「合計が A_i 以上になる最小枚数」= ceil(A_i / 1000) 枚なので、
// お釣りは r_i = 1000 * ceil(A_i / 1000) - A_i となり、必ず 0 <= r_i <= 999 に収まる。
//
// 「お釣りの硬貨の合計枚数が最小」は、額面が 1, 10, 100 という正準系 (小さい方が大きい方の
// 約数になっている) なので大きい額面から貪欲に取るのが最適で、その結果は r_i を 10 進表記
// したときの各桁そのものになる。つまり 100 円玉が r/100 枚、10 円玉が r/10%10 枚、
// 1 円玉が r%10 枚。額面が {1, 3, 4} のような非正準系だと貪欲は最適でなくなる
// (6 円を貪欲だと 4+1+1 の 3 枚、最適は 3+3 の 2 枚。typical90 016 のコメント参照)。
//
// ハマりどころは「お釣りを全部合計してから桁分解する」誤り。桁の繰り上がりが潰れて別物に
// なる。サンプル 1 なら r の合計は 704 + 890 + 999 = 2593 で 1 円玉 3 枚と出てしまうが、
// 正解は 4 + 0 + 9 = 13 枚。分解は買い物ごとに行い、足すのは金額ではなく枚数。
//
// 出力順は 1 円 -> 10 円 -> 100 円 で、桁の大きい順ではない点にも注意。
//
// N <= 1000 で 1 回あたり各額面 9 枚以下なので合計は高々 9000 枚。オーバーフローは無縁。

#[fastout]
fn main() {
    input! {
        n: usize,
        a: [usize; n],
    };

    let mut one = 0usize;
    let mut ten = 0usize;
    let mut hundred = 0usize;
    for ai in a {
        let div = ai / 1000;
        let modi = ai % 1000;

        let cnt_1000 = if modi != 0 { div + 1 } else { div };

        let remain = cnt_1000 * 1000 - ai;

        hundred += remain / 100;
        ten += remain % 100 / 10;
        one += remain % 10;
    }

    println!("{} {} {}", one, ten, hundred);
}

