// 身長 H[cm]、体重 W[kg] から BMI = W / (H/100)^2 が 25 以上かを判定する問題。
//
// 式をそのまま f64 で書くと「サンプルは通るのに WA」になる。H / 100.0 は 2 進数で
// 正確に表せないことが多く、BMI がちょうど 25 になる入力で商が 25 をわずかに下回る。
// 1 <= H, W <= 300 の全 90000 通りのうち (20,1) (40,4) (80,16) (160,64) (220,121) など
// 6 通りが Yes のはずなのに No になる。サンプル 3 の (180,81) もちょうど 25 だが、
// たまたま誤差が出ない側に転ぶので気づけない。
//
// なので判定は整数だけで行う。W / (H/100)^2 = W * 10000 / H^2 と変形すれば小数が消える。
// 整数の割り算は切り捨てだが、比較相手の 25 が整数なので判定は変わらない
// (x >= 25 と floor(x) >= 25 は同値。比較相手が 24.5 のような小数だとこれは成り立たない)。
//
// 型は W * 10000 が最大 300 * 10000 = 3 * 10^6 で、i32 の 2.1 * 10^9 にも収まる。
// H >= 1 なので 0 除算も起きない。

#[fastout]
fn main() {
    input! {
        h: usize,
        w: usize,
    };

    let ans = if w * 10000 / (h * h) >= 25 {
        "Yes"
    } else {
        "No"
    };

    println!("{ans}");
}

