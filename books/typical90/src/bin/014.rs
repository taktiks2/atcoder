//      パターンデフィート・クイックソートになり、マージソートと違って作業用の確保が
//      要らないぶん速い。競プロで安定性が必要な場面はほぼないので既定でこちら
// a.sort_unstable();
// b.sort_unstable();

// alt: abs_diff なら引き算を挟まずに差の絶対値が取れる。符号なし型で受けたときに
//      ai - bi がアンダーフローで panic する事故を構造的に防げる (i64 に対しては
//      u64 が返るので、受け側の型も u64 にする)
// let ans: u64 = a.iter().zip(&b).map(|(&ai, &bi)| ai.abs_diff(bi)).sum();

// alt: 一般化すると「コスト |A_i - B_j| の最小重み二部完全マッチング」で、素直に解くと
//      ハンガリアン法の O(N^3) になり N = 10^5 では乗らない。ただしソート後のコスト行列は
//      c[i][j] + c[i+1][j+1] <= c[i][j+1] + c[i+1][j] という Monge 条件 (上の交換論法
//      そのもの) を満たし、この形の行列では恒等マッチングが最適と分かっている。
//      「コストが Monge なら両方ソートして同順で組む」は他の問題にも効く定石

