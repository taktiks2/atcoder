// algo: greedy, sort, exchange-argument
use proconio::input;

// A と B をそれぞれ昇順ソートし、同じ順位どうしを組にしたときの距離の総和が答え。
// ソート O(N log N) が支配的で、N <= 10^5 なので余裕。
//
// なぜソート順でよいか 1: 交換論法。a1 <= a2, b1 <= b2 のとき常に
//     |a1 - b1| + |a2 - b2| <= |a1 - b2| + |a2 - b1|
// が成り立つ (数直線上で 2 本の線分を引くと、交差している方が必ず長い)。つまり
// 「交差した対応付け」はほどいても悪化しない。任意の対応付けは交差を 1 つずつ解消
// していけばコストを増やさずソート順へ変形できるので、交差のない唯一の形である
// ソート順が最適。
//
// なぜソート順でよいか 2: しきい値ごとの下界。|x - y| は「x と y の間にある実数 t
// の長さ」なので、総コスト = ∫ (座標 t をまたぐ組の本数) dt と書ける。ある t について
// p = #{A_i <= t}, q = #{B_j <= t} とし、両端とも t 以下である組の数を k とすると
// k <= min(p, q) なので、t をまたぐ組は (p - k) + (q - k) >= |p - q| 本以上あり、
// これがどの対応付けにも共通の下界になる。ソート順で組むと「両端が t 以下」になるのは
// ちょうど先頭 min(p, q) 組なので k = min(p, q) となり、すべての t で同時に下界
// |p - q| を達成する。よって積分した総コストも最小。
//
// 型は i64 必須。座標 <= 10^9, N <= 10^5 で総和は最大 10^14 程度になり i32 では溢れる。

fn main() {
    input! {
        n: usize,
        mut a: [i64; n],
        mut b: [i64; n],
    };

    a.sort();
    b.sort();

    let ans: i64 = a.iter().zip(&b).map(|(&ai, &bi)| (ai - bi).abs()).sum();

    println!("{ans}");
}

