// algo: brute-force, enumeration
use proconio::input;

// A 円硬貨を i 枚、B 円硬貨を j 枚と決め打つと、残額 x = N - A*i - B*j は C 円硬貨だけで
// 払うしかないので k = x / C と一意に定まる (x が C で割り切れるときのみ有効)。
// つまり全探索すべきは (i, j) の 2 変数だけで、3 重ループの O(10^12) が O(10^8) に落ちる。
// 枚数の合計は 9999 枚以下なので i + j <= 9999、探索数は 9999^2 / 2 ≈ 5×10^7 で間に合う。
//
// 貪欲 (大きい硬貨から取れるだけ取る) は不正解。硬貨の組が「正準系」とは限らないため。
// 反例: N = 6, (A, B, C) = (1, 3, 4) なら貪欲は 4 + 1 + 1 = 3 枚だが、最適は 3 + 3 = 2 枚。
//
// 金額での DP も不可。N <= 10^9 なので dp 配列が確保できない。逆に「枚数」は 9999 以下と
// 小さいので、状態を金額ではなく枚数側に持つ = i, j を回す、という発想になる。
//
// usize (符号なし) で持っているので、残額が負になるケースは引き算の前に弾く必要がある。
// ここでは checked_sub で「引けたら Some」として処理している。素直に引くと桁溢れで巨大な
// 正の数になり、x % c == 0 が偶然成立して誤答になりうる。
// なお a * i の最大は 10^9 × 9999 ≈ 10^13 なので 64bit には十分収まる。

fn main() {
    input! {
        n: usize,
        a: usize,
        b: usize,
        c: usize,
    };

    let mut ans = usize::MAX;

    for i in 0..=9999 {
        if a * i > n {
            break;
        }
        for j in 0..=9999 - i {
            let ai = a * i;
            let bj = b * j;

            if let Some(x) = n.checked_sub(ai + bj) {
                let k = x / c;
                let can_pay = (9999 - i - j) >= k && x % c == 0;
                if can_pay {
                    ans = ans.min(i + j + k);
                }
            }
        }
    }

    println!("{}", ans);
}

